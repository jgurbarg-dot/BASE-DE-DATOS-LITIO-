# ---------------- INTERFAZ ---------------- #
compuestos = cargar_datos()

compuesto = st.selectbox(
    "Seleccioná un compuesto:",
    list(compuestos.keys())
)

I = st.slider(
    "Fuerza iónica (I)",
    min_value=0.0,
    max_value=10.0,
    value=1.0
)

datos = compuestos[compuesto]

# ---------------- CÁLCULO ---------------- #
b0 = datos["Químicas"].get("Pitzer_beta0", 0)
b1 = datos["Químicas"].get("Pitzer_beta1", 0)

gamma = calcular_gamma(b0, b1, I)

# ---------------- RESULTADOS ---------------- #
st.subheader(f"📊 Resultados para: {compuesto}")
st.metric("Coeficiente de actividad (γ)", f"{gamma:.4f}")

