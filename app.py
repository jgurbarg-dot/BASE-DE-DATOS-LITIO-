# ---------------- FUNCIÓN PITZER ---------------- #
def calcular_gamma(b0, b1, I):
    return math.exp(
        -0.51 * (math.sqrt(I) / (1 + 1.2 * math.sqrt(I)))
        + I * b0
        + I * b1
    )

# ---------------- CONFIG APP ---------------- #
